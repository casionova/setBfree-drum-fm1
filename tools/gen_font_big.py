"""B3+DRUM: the big-type fonts, firmware/gen/font_big.h, in felucca_font_t's format (gfx.c: 4-bit grey, two pixels a
byte, high nibble first, rows of (w + 1) / 2 bytes).

  FONT_M   Terminus 24 px bold, ASCII 32..126: the screens' text
  FONT_XL  Terminus 32 px bold, ASCII 32..95 (upper case; lower case folds to it): the pop-ups

Terminus (SIL Open Font License 1.1, assets/fonts/Terminus-LICENSE.txt) as the PCF files of Debian/Ubuntu's
xfonts-terminus package (ter-u24b_iso-8859-1.pcf.gz, ter-u32b_iso-8859-1.pcf.gz). Needs Pillow.

  python3 tools/gen_font_big.py [/usr/share/fonts/X11/misc] > firmware/gen/font_big.h
"""
import gzip, io, os, sys, tempfile
from PIL import Image, ImageDraw, ImageFont, PcfFontFile

def load(path):
    """a PCF (gzipped or not) as a Pillow bitmap font"""
    raw = open(path, "rb").read()
    if path.endswith(".gz"):
        raw = gzip.decompress(raw)
    tmp = tempfile.mkdtemp()
    base = os.path.join(tmp, "f")
    PcfFontFile.PcfFontFile(io.BytesIO(raw)).save(base)
    return ImageFont.load(base + ".pil")

def emit(name, font, w, h, first, last, out):
    data, offs, adv, bws = [], [], [], []
    bpr = (w + 1) // 2
    for ch in range(first, last + 1):
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((0, 0), chr(ch), font=font, fill=255)
        px = im.load()
        offs.append(len(data))
        for y in range(h):
            for x in range(0, w, 2):
                a = 15 if px[x, y] >= 128 else 0
                b = 15 if x + 1 < w and px[x + 1, y] >= 128 else 0
                data.append(a << 4 | b)
        adv.append(w)
        bws.append(w)
    n = last - first + 1
    out.write("static const uint8_t %s_DATA[%d] = {" % (name, len(data)))
    for i, v in enumerate(data):
        out.write(("\n    " if i % 24 == 0 else "") + "0x%02x," % v)
    out.write("\n};\n")
    out.write("static const uint16_t %s_OFF[%d] = {%s};\n" % (name, n, ", ".join(map(str, offs))))
    out.write("static const uint8_t %s_ADV[%d] = {%s};\n" % (name, n, ", ".join(map(str, adv))))
    out.write("static const uint8_t %s_BW[%d] = {%s};\n" % (name, n, ", ".join(map(str, bws))))
    out.write("static const felucca_font_t %s = { %d, 0, %d, %d, %s_ADV, %s_BW, %s_OFF, %s_DATA };\n\n"
              % (name, h, first, last, name, name, name, name))

def main():
    d = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/X11/misc"
    out = sys.stdout
    out.write("/* generated by tools/gen_font_big.py from Terminus ter-u24b and ter-u32b (iso-8859-1), SIL OFL 1.1 */\n")
    out.write("#pragma once\n#include <stdint.h>\n\n")
    emit("FONT_M", load(os.path.join(d, "ter-u24b_iso-8859-1.pcf.gz")), 12, 24, 32, 126, out)
    emit("FONT_XL", load(os.path.join(d, "ter-u32b_iso-8859-1.pcf.gz")), 16, 32, 32, 95, out)

if __name__ == "__main__":
    main()
