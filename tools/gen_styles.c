/* B3+DRUM: CB-931's rhythm styles (tools/cb931/factory_styles.c and vl1_styles.h: the CR-78's 20, the VL-1's 10) as the
 * firmware's tables, firmware/src/drum_styles.h, for its player (drum_seq.h). Runs on the computer: tools/gen_drums.sh.
 * A style: name, beats a bar (4 or 3), its swing, and six parts (intro, main A, fill into B, main B, fill into A, outro),
 * each a number of bars and its hits (tick on a 12-a-beat grid, kit slot, velocity). */
#include <stdio.h>
#include "rhythm.h"

static void cstr(const char *s)
{
    putchar('"');
    for (; s && *s; s++) putchar(*s == '"' ? '\'' : *s);
    putchar('"');
}

int main(void)
{
    int n = rh_style_count(), i, p, h, total = 0;
    printf("/* Generated by tools/gen_styles.c from tools/cb931/factory_styles.c and vl1_styles.h (CB-931 0.16.1): do not edit.\n"
           " * Main A of each of the first 20 is a Roland CR-78 preset rhythm, from CW-78's transcription of the CR-78 service\n"
           " * notes (github.com/charlesvestal/schwung-cw-78, GPL-3.0); their other parts are CB-931's. The last 10: the VL-1's. */\n");
    printf("#ifndef DRUM_STYLES_H\n#define DRUM_STYLES_H\n\n#define DRS_STYLES %du\n\n", n);
    for (i = 0; i < n; i++) {
        const rh_style *s = rh_style_get(i);
        for (p = 0; p < RH_PARTS; p++) {
            const rh_part *pt = &s->part[p];
            printf("static const drs_hit_t DRS_%d_%d[%d] = {", i, p, pt->n > 0 ? pt->n : 1);
            for (h = 0; h < pt->n; h++) printf("%s{%u,%u,%u}", h ? "," : "", pt->hits[h].tick, pt->hits[h].slot, pt->hits[h].vel);
            if (pt->n <= 0) printf("{0,0,0}");
            printf("};\n");
            total += pt->n;
        }
    }
    printf("\nstatic const drs_style_t DRS_STYLE[DRS_STYLES] = {\n");
    for (i = 0; i < n; i++) {
        const rh_style *s = rh_style_get(i);
        printf("    { ");
        cstr(s->name);
        printf(", %u, %u, {", s->beats, rh_style_swing(s));
        for (p = 0; p < RH_PARTS; p++)
            printf("%s{%u, %d, DRS_%d_%d}", p ? ", " : "", s->part[p].bars > 0 ? s->part[p].bars : 1, s->part[p].n, i, p);
        printf("} },\n");
    }
    printf("};\n\n/* %d hits in all */\n#endif\n", total);
    return 0;
}
